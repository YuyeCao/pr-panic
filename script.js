  function calculatePersona(history) {
    const scores = {};
    const lateScores = {};
    Object.keys(personas).forEach((key) => {
      scores[key] = 0;
      lateScores[key] = 0;
    });

    history.forEach((entry) => {
      const weight = ROUND_WEIGHTS[entry.round - 1];
      Object.entries(personas).forEach(([key, persona]) => {
        const contribution = entry.choice.tags.reduce((sum, tag) => sum + (persona.profile[tag] || 0), 0) * weight;
        scores[key] += contribution;
        if (entry.round >= 3) lateScores[key] += contribution;
      });
    });

    const ranked = Object.keys(personas).sort((a, b) => {
      const difference = scores[b] - scores[a];
      if (Math.abs(difference) > 0.35) return difference;
      const lateDifference = lateScores[b] - lateScores[a];
      if (Math.abs(lateDifference) > 0.01) return lateDifference;
      return Object.keys(personas).indexOf(a) - Object.keys(personas).indexOf(b);
    });
    return personas[ranked[0]];
  }

