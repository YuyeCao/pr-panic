      function calculatePersonaV2(history) {
        const scores = {};
        const lateScores = {};
        Object.keys(personas).forEach((key) => { scores[key] = 0; lateScores[key] = 0; });
        history.forEach((entry) => {
          const weight = ROUND_WEIGHTS[entry.round - 1];
          Object.entries(personas).forEach(([key, persona]) => {
            const amount = entry.choice.tags.reduce((sum, tag) => sum + (persona.profile[tag] || 0), 0) * weight;
            scores[key] += amount;
            if (entry.round >= 3) lateScores[key] += amount;
          });
        });
        const ranked = Object.keys(personas).sort((a, b) => {
          const difference = scores[b] - scores[a];
          if (Math.abs(difference) > 0.35) return difference;
          const lateDifference = lateScores[b] - lateScores[a];
          return Math.abs(lateDifference) > 0.01 ? lateDifference : Object.keys(personas).indexOf(a) - Object.keys(personas).indexOf(b);
        });
        return { key: ranked[0], scores };
      }

      function calculateTendenciesV2(history) {
        const totals = Object.fromEntries(tendencyLabelsV2.map((label) => [label, 0]));
        history.forEach((entry) => entry.choice.tags.forEach((tag) => { totals[tag] += ROUND_WEIGHTS[entry.round - 1]; }));
        const max = Math.max(...Object.values(totals), 1);
        return tendencyLabelsV2.map((label) => ({ label, percent: Math.round((totals[label] / max) * 100) }));
      }

      function getDisplayedTendenciesV2(history) {
        const tendencies = Object.fromEntries(calculateTendenciesV2(history).map((item) => [item.label, item.percent]));
        return tendencyDisplayMapV2.map(([source, label]) => ({ label, percent: tendencies[source] }));
      }

